#int
a = 10
print(type(a), a)

#float
b = 10.5
print(type(b), b)

#str
c = "Hello"
print(type(c), c)

#bool
d = True 
print(type(d), d)

#complex
e = 10 + 2j
print(type(e), e)

#list
f = [1, 2, 3, 4, 5]
print(type(f), f)

#tuple
g = (1, 2, 3, 4, 5)
print(type(g), g)

#set
h = {1, 2, 3, 4, 5}
print(type(h), h)

#dict
i = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five"}
print(type(i), i)

# None 
is_valid = None
print(type(is_valid), is_valid)

#bytes
b = b"Hello"
print(type(b), b)

